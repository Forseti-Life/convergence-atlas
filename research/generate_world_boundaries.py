"""Convert Natural Earth's public-domain 1:50m countries to SVG map paths."""

import hashlib
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ALIASES = {
    "Democratic Republic of the Congo": "Congo, Democratic Republic of the",
    "Republic of the Congo": "Congo, Republic of the",
    "eSwatini": "Eswatini",
    "Vatican": "Holy See (Observer State)",
    "São Tomé and Principe": "Sao Tome and Principe",
    "Palestine": "State of Palestine (Observer State)",
    "Turkey": "Türkiye",
}


def ring_path(ring):
    """Quantize coordinates and remove duplicate adjacent SVG vertices."""
    points = []
    for lon, lat in ring:
        point = f"{lon + 180:.2f},{90 - lat:.2f}"
        if not points or point != points[-1]:
            points.append(point)
    return "M" + "L".join(points) + "Z"


def main(source):
    raw = Path(source).read_bytes()
    features = json.loads(raw)["features"]
    countries = set(re.findall(r'^  "(.*)",', (ROOT / "web/countries.mjs").read_text(), re.M))
    boundaries = []
    matched = set()
    for feature in features:
        props = feature["properties"]
        name = next(
            (candidate for key in ("ADMIN", "NAME_LONG", "NAME")
             if (candidate := ALIASES.get(props[key], props[key])) in countries),
            None,
        )
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        boundaries.append({
            "name": name,
            "label": props["ADMIN"],
            "marker": sum(
                abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(polygon[0], polygon[0][1:]))) / 2
                for polygon in polygons
            ) < 0.3,
            "path": "".join(ring_path(ring) for polygon in polygons for ring in polygon),
        })
        if name:
            matched.add(name)
    missing = countries - matched
    if missing:
        raise ValueError(f"Model countries missing geographic boundaries: {sorted(missing)}")
    output = "// Generated by research/generate_world_boundaries.py; Natural Earth public domain.\n"
    output += f"// Source SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
    output += "export const WORLD_BOUNDARIES = " + json.dumps(boundaries, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "web/world-boundaries.mjs").write_text(output)
    print(f"Generated {len(boundaries)} geographic features covering {len(matched)} model countries.")


if __name__ == "__main__":
    main(sys.argv[1])
