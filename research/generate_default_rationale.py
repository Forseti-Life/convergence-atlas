#!/usr/bin/env python3
"""Generate default-value rationale documentation and browser data."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "research/defaults-rationale.v1.json"
CATALOG = ROOT / "research/source-catalog.v1.json"
DOC = ROOT / "docs/DEFAULT_VALUES.md"
WEB = ROOT / "web/default-rationales.mjs"
MANIFEST = ROOT / "research/defaults-rationale-manifest.json"


def display(value) -> str:
    if isinstance(value, float) and 0 <= value <= 1:
        return f"{value * 100:g}%"
    if isinstance(value, list):
        return "–".join(display(item) for item in value)
    return str(value)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    rationale = json.loads(SOURCE.read_text())
    catalog = json.loads(CATALOG.read_text())
    sources = {item["id"]: item for item in catalog["sources"]}
    lines = [
        "# Default Value Rationale",
        "",
        f"**Version:** {rationale['rationaleVersion']}  ",
        f"**Frozen:** {rationale['frozenAt']}",
        "",
        "> Existing research and observed proxies justify variable inclusion and default scale. Only Tier A values are direct observations. Tier D values are transparent scenario conventions, not empirical estimates.",
        "",
        "## Evidence tiers",
        "",
        "| Tier | Meaning |",
        "|---|---|",
    ]
    for tier, meaning in rationale["evidenceTiers"].items():
        lines.append(f"| {tier} | {meaning} |")
    lines.extend([
        "",
        "## Active defaults",
        "",
        "| Variable | Default | Range | Tier | Confidence | Sensitivity required |",
        "|---|---:|---:|---|---|---:|",
    ])
    for item in rationale["defaults"]:
        lines.append(f"| `{item['id']}` | {display(item['default'])} | {display(item['range'])} | {item['tier']} | {item['confidence']} | {'Yes' if item['sensitivityRequired'] else 'No'} |")
    for item in rationale["defaults"]:
        lines.extend([
            "",
            f"## `{item['id']}` — default {display(item['default'])}",
            "",
            f"- **Evidence tier:** {item['tier']}",
            f"- **Confidence:** {item['confidence']}",
            f"- **Rationale:** {item['rationale']}",
            f"- **Derivation:** {item['derivation']}",
            f"- **Sensitivity:** {'Required' if item['sensitivityRequired'] else 'Not required; display setting'}",
        ])
        source_links = [f"[{sources[source]['name']}]({sources[source]['url']})" for source in item["sourceIds"]]
        source_links += [f"[Additional source]({url})" for url in item["additionalSources"]]
        lines.append("- **Sources:** " + ("; ".join(source_links) if source_links else "None — display convention"))
    lines.extend(["", "## Hidden constants", ""])
    for item in rationale["hiddenConstants"]:
        lines.extend([
            f"### `{item['id']}` = {display(item['value'])}",
            "",
            f"- **Tier:** {item['tier']}",
            f"- **Confidence:** {item['confidence']}",
            f"- **Rationale:** {item['rationale']}",
            f"- **Sensitivity required:** {'Yes' if item['sensitivityRequired'] else 'No'}",
            "",
        ])
    lines.extend([
        "## Interpretation rule",
        "",
        "A citation justifies considering a variable; it does not automatically validate the model's equation or default. Proxy and conventional defaults remain subject to scenario and sensitivity analysis.",
        "",
    ])
    DOC.write_text("\n".join(lines))
    WEB.write_text(
        "// Generated by research/generate_default_rationale.py; do not edit manually.\n"
        f"export const DEFAULT_RATIONALES = Object.freeze({json.dumps(rationale, separators=(',', ':'))});\n"
    )
    manifest = {
        "version": rationale["rationaleVersion"],
        "sourceSha256": sha(SOURCE),
        "catalogSha256": sha(CATALOG),
        "documentSha256": sha(DOC),
        "webModuleSha256": sha(WEB),
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated rationale for {len(rationale['defaults'])} defaults and {len(rationale['hiddenConstants'])} hidden constants")


if __name__ == "__main__":
    main()
