#!/usr/bin/env python3
"""Validate the first COW empirical baseline artifacts."""

from __future__ import annotations

import json
import math
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "analysis" / "output"


def main() -> None:
    subprocess.run(
        ["python3", str(ROOT / "analysis/cow_empirical_baseline.py")],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    json_path = OUTPUT / "cow-empirical-baseline.json"
    report_path = OUTPUT / "COW_EMPIRICAL_BASELINE.md"
    web_path = ROOT / "web/validation-results.mjs"
    results = json.loads(json_path.read_text())

    assert results["metadata"]["version"] == "v2024"
    assert results["metadata"]["analysisType"] == "empirical membership-spell baseline"
    assert results["spells"] == 244
    assert results["observedExits"] > 0
    assert results["rightCensored"] > 0
    assert results["observedExits"] + results["rightCensored"] == results["spells"]
    assert 0 < results["annualExitHazard"] < 0.1
    assert results["bootstrap"]["iterations"] == 2000
    assert results["bootstrap"]["seed"] == 20261006
    assert results["bootstrap"]["lower95"] < results["annualExitHazard"] < results["bootstrap"]["upper95"]

    survival = [row["survival"] for row in results["kaplanMeier"]]
    assert all(0 <= value <= 1 for value in survival)
    assert all(survival[index] >= survival[index + 1] for index in range(len(survival) - 1))

    backtests = results["rollingBacktest"]
    assert len(backtests) == 6
    assert all(row["riskSet"] > 0 for row in backtests)
    assert all(0 <= row["predictedExitRisk"] <= 1 for row in backtests)
    assert all(math.isfinite(row["brier"]) for row in backtests)

    report = report_path.read_text()
    assert "not automatically a collapse" in report
    assert "constant-hazard" in report
    assert "competing risks blocked" in report
    web = web_path.read_text()
    assert web.startswith("// Generated by analysis/cow_empirical_baseline.py")
    assert "EMPIRICAL_RESULTS" in web

    print("✓ empirical COW membership-spell survival baseline")
    print("✓ deterministic 2,000-sample bootstrap interval")
    print("✓ six rolling-origin constant-hazard backtests")
    print("✓ JSON, Markdown, and browser result artifacts")
    print("Empirical baseline validation passed.")


if __name__ == "__main__":
    main()
