#!/usr/bin/env python3
"""Validate generated PCA and scenario-analysis artifacts."""

from __future__ import annotations

import csv
import json
import math
import subprocess
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "analysis" / "output"


def main() -> None:
    csv_path = OUTPUT / "scenario-results.csv"
    json_path = OUTPUT / "pca-results.json"
    report_path = OUTPUT / "PCA_REPORT.md"
    web_path = ROOT / "web" / "analysis-results.mjs"

    for path in (csv_path, json_path, report_path, web_path):
        assert path.exists() and path.stat().st_size > 0, f"missing analysis artifact: {path}"

    before = csv_path.read_bytes()
    subprocess.run(
        ["node", str(ROOT / "analysis" / "generate_scenarios.mjs")],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    assert csv_path.read_bytes() == before, "scenario generation must be deterministic"

    with csv_path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    assert len(rows) == 768
    assert len({row["archetype"] for row in rows}) == 12
    assert sum(int(row["variant"]) == 0 for row in rows) == 12
    assert all(0 <= float(row["apexReached"]) <= 1 for row in rows)
    assert all(0 <= float(row["apexInfluenceYear500"]) <= 1 for row in rows)
    assert all(int(row["apexCalendarYearCapped"]) >= 2026 for row in rows)

    results = json.loads(json_path.read_text(encoding="utf-8"))
    assert results["metadata"]["baseYear"] == 2026
    assert results["metadata"]["horizonCalendarYear"] == 7026
    assert results["metadata"]["rows"] == 768
    assert results["metadata"]["archetypes"] == 12
    assert results["metadata"]["analysisType"] == "synthetic model-behavior PCA"

    components = results["pca"]["components"]
    explained_total = sum(component["explainedVariance"] for component in components)
    assert math.isclose(explained_total, 1.0, abs_tol=1e-9)
    assert all(
        components[index]["cumulativeVariance"] <= components[index + 1]["cumulativeVariance"]
        for index in range(len(components) - 1)
    )
    assert len(components) == len(results["pca"]["variables"])
    assert all(len(component["loadings"]) == len(results["pca"]["variables"]) for component in components)
    variables = results["pca"]["variables"]
    vectors = np.array([
        [
            next(item["loading"] for item in component["loadings"] if item["variable"] == variable)
            for variable in variables
        ]
        for component in components
    ])
    assert np.allclose(vectors @ vectors.T, np.eye(len(vectors)), atol=1e-9), "PCA vectors must be orthonormal"
    assert len(results["archetypes"]) == 12
    assert len(results["sensitivity"]) == len(results["pca"]["variables"])

    report = report_path.read_text(encoding="utf-8")
    assert "not empirical inference" in report
    assert "Right-censored" in report
    assert "Scenario outcomes" in report
    assert "Median Apex calendar year" in report
    assert "7026" in report

    web = web_path.read_text(encoding="utf-8")
    assert web.startswith("// Generated by analysis/pca_analysis.py")
    assert "ANALYSIS_RESULTS" in web

    print("✓ 768 deterministic scenario variants across 12 archetypes")
    print("✓ byte-identical regeneration and orthonormal PCA vectors")
    print("✓ PCA variance, cumulative ordering, and loading dimensions")
    print("✓ scenario, sensitivity, Markdown, JSON, and browser artifacts")
    print("Analysis validation passed.")


if __name__ == "__main__":
    main()
